import logging
from time import perf_counter

from sqlalchemy.exc import SQLAlchemyError

from src.api.schemas.chat import (
    ChatDiagnostics,
    ChatDiagnosticsTimings,
    ChatMetadata,
    ChatResponse,
    VisualizationSuggestion,
)
from src.application.services.context_builder import ContextBuilder
from src.application.services.insight_service import InsightService
from src.application.services.visualization_service import VisualizationService
from src.domain.exceptions.errors import UnsafeSQLError
from src.domain.interfaces.datasource import DataSource
from src.domain.interfaces.text_to_sql import TextToSQLService
from src.security.validators.sql_validator import SQLValidator

logger = logging.getLogger(__name__)


class ChatUseCase:
    def __init__(
        self,
        context_builder: ContextBuilder,
        text_to_sql_service: TextToSQLService,
        sql_validator: SQLValidator,
        data_source: DataSource,
        insight_service: InsightService,
        visualization_service: VisualizationService,
        provider_name: str,
    ):
        self.context_builder = context_builder
        self.text_to_sql_service = text_to_sql_service
        self.sql_validator = sql_validator
        self.data_source = data_source
        self.insight_service = insight_service
        self.visualization_service = visualization_service
        self.provider_name = provider_name

    def execute(
        self,
        message: str,
        organization_id: str,
        response_mode: str = 'basic',
    ) -> ChatResponse:
        start_time = perf_counter()
        timings = ChatDiagnosticsTimings()
        sql_generated = False
        sql_validated = False
        query_executed = False

        context_start = perf_counter()
        context = self.context_builder.build(organization_id=organization_id)
        timings.context_build_ms = int((perf_counter() - context_start) * 1000)

        generation_start = perf_counter()
        generation_result = self.text_to_sql_service.generate_sql(
            question=message,
            context=context,
            organization_id=organization_id,
        )
        timings.sql_generation_ms = int((perf_counter() - generation_start) * 1000)
        sql = generation_result.sql
        sql_source = generation_result.source
        sql_generated = bool(sql)

        if not sql:
            logger.warning('Unable to generate valid SQL for request | source=%s', sql_source)
            return self._build_unavailable_response(
                start_time=start_time,
                sql_source=sql_source,
                response_mode=response_mode,
                timings=timings,
                sql_generated=sql_generated,
                sql_validated=sql_validated,
                query_executed=query_executed,
                message=(
                    'Nao foi possivel atender a solicitacao com seguranca. '
                    'Reformule a pergunta com mais contexto e tente novamente.'
                ),
            )

        try:
            validation_start = perf_counter()
            safe_sql = self.sql_validator.validate_and_rewrite(
                sql=sql,
                organization_id=organization_id,
            )
            timings.sql_validation_ms = int((perf_counter() - validation_start) * 1000)
            sql_validated = True
        except UnsafeSQLError as exc:
            logger.warning(
                'Invalid SQL generated by model, aborting execution | reason=%s | sql=%s',
                str(exc),
                sql,
            )
            return self._build_unavailable_response(
                start_time=start_time,
                sql_source='validation_failed',
                response_mode=response_mode,
                timings=timings,
                sql_generated=sql_generated,
                sql_validated=sql_validated,
                query_executed=query_executed,
                message=(
                    'A solicitacao nao pode ser atendida porque a consulta gerada '
                    'nao passou nas validacoes de seguranca.'
                ),
            )

        try:
            execution_start = perf_counter()
            columns, rows = self.data_source.execute_query(safe_sql)
            timings.query_execution_ms = int((perf_counter() - execution_start) * 1000)
            query_executed = True
        except SQLAlchemyError:
            logger.warning('SQL execution failed after validation', exc_info=True)
            return self._build_unavailable_response(
                start_time=start_time,
                sql_source='execution_failed',
                response_mode=response_mode,
                timings=timings,
                sql_generated=sql_generated,
                sql_validated=sql_validated,
                query_executed=query_executed,
                message=(
                    'A solicitacao nao pode ser atendida no momento porque a consulta '
                    'nao conseguiu ser executada com seguranca.'
                ),
            )

        self._auto_train_after_success(
            question=message,
            sql=safe_sql,
            rows=rows,
            organization_id=organization_id,
            sql_source=sql_source,
        )
        insight_start = perf_counter()
        answer, used_fallback_answer = self.insight_service.generate(
            question=message,
            sql=safe_sql,
            result=rows,
            response_mode=response_mode,
        )
        timings.insight_generation_ms = int((perf_counter() - insight_start) * 1000)

        visualization_start = perf_counter()
        visualization = self.visualization_service.suggest(
            question=message,
            columns=columns,
        )
        timings.visualization_ms = int((perf_counter() - visualization_start) * 1000)

        elapsed_ms = int((perf_counter() - start_time) * 1000)
        timings.total_ms = elapsed_ms

        return ChatResponse(
            answer=answer,
            sql=safe_sql,
            columns=columns,
            rows=rows,
            visualization=VisualizationSuggestion(**visualization),
            metadata=ChatMetadata(
                provider=self.provider_name,
                execution_time_ms=elapsed_ms,
                response_mode=response_mode,
                sql_source=sql_source,
                row_count=len(rows),
                column_count=len(columns),
            ),
            diagnostics=ChatDiagnostics(
                sql_generated=sql_generated,
                sql_validated=sql_validated,
                query_executed=query_executed,
                used_fallback_answer=used_fallback_answer,
                rows_returned=len(rows),
                columns_returned=len(columns),
                visualization_type=visualization.get('type', 'table'),
                timings=timings,
            ),
        )

    def _auto_train_after_success(
        self,
        question: str,
        sql: str,
        rows: list[dict],
        organization_id: str,
        sql_source: str,
    ) -> None:
        # Mirror Vanna 0.7 auto_train behavior: only learn when result has rows.
        if not rows:
            return

        if sql_source != 'vanna_generated':
            return

        train_method = getattr(self.text_to_sql_service, 'train_question_sql', None)
        if not callable(train_method):
            return

        try:
            train_method(
                organization_id=organization_id,
                question=question,
                sql=sql,
            )
        except Exception:
            logger.warning('Unable to auto-train Vanna question_sql pair', exc_info=True)

    def _build_unavailable_response(
        self,
        start_time: float,
        sql_source: str,
        response_mode: str,
        timings: ChatDiagnosticsTimings,
        sql_generated: bool,
        sql_validated: bool,
        query_executed: bool,
        message: str,
    ) -> ChatResponse:
        elapsed_ms = int((perf_counter() - start_time) * 1000)
        timings.total_ms = elapsed_ms
        return ChatResponse(
            answer=message,
            sql='',
            columns=[],
            rows=[],
            visualization=VisualizationSuggestion(type='table'),
            metadata=ChatMetadata(
                provider=self.provider_name,
                execution_time_ms=elapsed_ms,
                response_mode=response_mode,
                sql_source=sql_source,
                row_count=0,
                column_count=0,
            ),
            diagnostics=ChatDiagnostics(
                sql_generated=sql_generated,
                sql_validated=sql_validated,
                query_executed=query_executed,
                used_fallback_answer=False,
                rows_returned=0,
                columns_returned=0,
                visualization_type='table',
                timings=timings,
            ),
        )
